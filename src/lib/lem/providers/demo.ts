function pick<T>(arr: T[], rnd: () => number): T {
  return arr[Math.floor(rnd() * arr.length)]
}

function mulberry(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function fill(template: string, v: Vocab, rnd: () => number): string {
  return template
    .replace(/\{event\}/g, () => pick(v.events, rnd))
    .replace(/\{force\}/g, () => pick(v.forces, rnd))
    .replace(/\{thing\}/g, () => pick(v.things, rnd))
    .replace(/\{role\}/g, () => pick(v.roles, rnd))
    .replace(/\{place\}/g, () => pick(v.places, rnd))
}

const TONE_CYCLE: Tone[] = ['dark', 'neutral', 'light', 'ironic', 'dark', 'neutral', 'light', 'ironic', 'dark', 'light']

export function generateDemoWave(spec: WaveSpec): { options: { title: string; description: string; consequences: string; tone: Tone; tags: string[] }[]; quip?: string } {
  const seed = spec.level * 7919 + spec.category.length * 31 + spec.n * 13 + (spec.premise?.length ?? 0)
  const rnd = mulberry(seed + Date.now() % 1000)
  const v = BANKS[spec.category] ?? BANKS['Психологическая проза']
  const titles = TITLES[spec.act] ?? TITLES['Завязка']
  const descs = DESCS[spec.act] ?? DESCS['Завязка']

  const excluded = new Set(spec.excludedTitles.map((t) => t.toLowerCase()))
  const options: { title: string; description: string; consequences: string; tone: Tone; tags: string[] }[] = []
  const usedTitles = new Set<string>()

  let toneIdx = Math.floor(rnd() * TONE_CYCLE.length)
  let guard = 0
  while (options.length < spec.n && guard < 200) {
    guard++
    const title = fill(pick(titles, rnd), v, rnd)
    if (usedTitles.has(title.toLowerCase()) || excluded.has(title.toLowerCase())) continue
    usedTitles.add(title.toLowerCase())
    const desc = fill(pick(descs, rnd), v, rnd)
    const cons = fill(pick(CONS, rnd), v, rnd)
    const tone = TONE_CYCLE[toneIdx % TONE_CYCLE.length]
    toneIdx += 1 + Math.floor(rnd() * 2)
    const tags = Array.from(new Set([pick(v.forces, rnd).split(' ')[0].toLowerCase(), pick(['ставки', 'тайна', 'выбор', 'риск', 'доверие', 'цена'], rnd)])).slice(0, 3)
    options.push({ title, description: desc, consequences: cons, tone, tags })
  }

  // минимум один «лобовой» и один неожиданный вариант гарантированы порядком шаблонов
  return {
    options: options.slice(0, 10),
    quip: spec.lem ? pick(QUIPS, rnd) : undefined,
  }
}

export const demoAdapter: LLMAdapter = {
  code: 'demo',
  async generate(_cfg: ProviderConfig, _system: string, _user: string, opts?: GenerateOpts): Promise<LLMResult> {
    const spec = opts?.wave
    if (!spec) throw new Error('Демо-генератору не переданы данные волны')
    await new Promise((r) => setTimeout(r, 500 + Math.random() * 400))
    const wave = generateDemoWave(spec)
    const payload = { act: spec.act, level: spec.level, options: wave.options, quip: wave.quip }
    return { raw: JSON.stringify(payload, null, 2), tokensIn: 0, tokensOut: 0, model: 'demo-templates' }
  },
  async test(cfg: ProviderConfig): Promise<TestResult> {
    return { ok: true, latencyMs: 3, model: cfg.model }
  },
}
